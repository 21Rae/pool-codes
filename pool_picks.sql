CREATE OR REPLACE TRIGGER trg_delete_betking_space_view
INSTEAD OF DELETE ON public."weekly pool picks (betking)"
FOR EACH ROW EXECUTE FUNCTION delete_from_pool_picks_view();

CREATE OR REPLACE TRIGGER trg_delete_betking_clean_view
