INSTEAD OF DELETE ON public."weekly pool picks(Bet9ja)"
FOR EACH ROW EXECUTE FUNCTION delete_from_pool_picks_view();

CREATE OR REPLACE TRIGGER trg_delete_bet9ja_space_view
INSTEAD OF DELETE ON public."weekly pool picks (Bet9ja)"
FOR EACH ROW EXECUTE FUNCTION delete_from_pool_picks_view();

