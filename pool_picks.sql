-- STEP 1: CLEAN UP CONFLICTING OBJECTS IF PRESENT
DO $$
DECLARE
    r RECORD;
BEGIN
    FOR r IN (
        SELECT table_name, table_type 
        FROM information_schema.tables 
        WHERE table_schema = 'public' 
          AND table_name IN (
            'weekly pool picks(Bet9ja)', 'weekly pool picks (Bet9ja)', 'weekly pool picks(bet9ja)', 'weekly pool picks (bet9ja)',
            'weekly pool picks(betking)', 'weekly pool picks (betking)', 'weekly pool picks(Betking)', 'weekly pool picks (Betking)',
            'weekly pool picks', 'weekly_pool_picks', 'weekly_pool_picks_bet9ja', 'weekly_pool_picks_betking'
          )
    ) LOOP
        IF r.table_type = 'VIEW' THEN
            EXECUTE format('DROP VIEW IF EXISTS public.%I CASCADE', r.table_name);
        END IF;
    END LOOP;
END $$;

-- Drop pool_picks if rebuilding schema
DROP TABLE IF EXISTS public.pool_picks CASCADE;

-- ----------------------------------------------------------------------------
-- STEP 2: CREATE CORE pool_picks TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE public.pool_picks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pool INT NOT NULL,
  pool_no INT,
  bet_code VARCHAR(50),
  home VARCHAR(150) NOT NULL,
  away VARCHAR(150) NOT NULL,
  home_win NUMERIC(5,2),
  draw_x NUMERIC(5,2) NOT NULL,
  away_win NUMERIC(5,2),
  bet VARCHAR(50) DEFAULT 'X',
  status VARCHAR(50) DEFAULT 'Saturday',
  kick_off VARCHAR(50) DEFAULT '3:00 PM',
  is_banker BOOLEAN DEFAULT FALSE,
  week_no INT DEFAULT 16,
  week INT DEFAULT 16,
  bookmaker VARCHAR(50) DEFAULT 'bet9ja',
  notes TEXT,
  league VARCHAR(100),
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Indexing for high-speed queries by bookmaker and week
CREATE INDEX idx_pool_picks_bookmaker ON public.pool_picks(bookmaker);
CREATE INDEX idx_pool_picks_week_no ON public.pool_picks(week_no);
CREATE INDEX idx_pool_picks_pool ON public.pool_picks(pool);
CREATE INDEX idx_pool_picks_is_banker ON public.pool_picks(is_banker);

-- ----------------------------------------------------------------------------
-- STEP 3: COLUMN SYNCHRONIZATION TRIGGER (pool <=> pool_no, week_no <=> week)
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION sync_pool_picks_compat()
RETURNS TRIGGER AS $$
BEGIN
  IF NEW.pool IS NULL AND NEW.pool_no IS NOT NULL THEN
    NEW.pool := NEW.pool_no;
  ELSIF NEW.pool_no IS NULL AND NEW.pool IS NOT NULL THEN
    NEW.pool_no := NEW.pool;
  END IF;

  IF NEW.week_no IS NULL AND NEW.week IS NOT NULL THEN
    NEW.week_no := NEW.week;
  ELSIF NEW.week IS NULL AND NEW.week_no IS NOT NULL THEN
    NEW.week := NEW.week_no;
  END IF;

  IF NEW.bookmaker IS NULL THEN
    NEW.bookmaker := 'bet9ja';
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_sync_pool_picks
BEFORE INSERT OR UPDATE ON public.pool_picks
FOR EACH ROW EXECUTE FUNCTION sync_pool_picks_compat();

-- ----------------------------------------------------------------------------
-- STEP 4: PERMISSIONS & RLS CONFIGURATION (ENABLES COMPLETE ADMIN DELETION)
-- ----------------------------------------------------------------------------
-- By default in Supabase, enabling RLS without a DELETE policy blocks all deletions.
-- We grant full permissions and add explicit permissive policies.
ALTER TABLE public.pool_picks ENABLE ROW LEVEL SECURITY;

-- Permissive policy allowing SELECT, INSERT, UPDATE, and DELETE for all roles
DROP POLICY IF EXISTS "Public full access on pool_picks" ON public.pool_picks;
CREATE POLICY "Public full access on pool_picks"
ON public.pool_picks
FOR ALL
TO public
USING (true)
WITH CHECK (true);

-- Grant privileges to standard Supabase roles
GRANT ALL ON public.pool_picks TO anon, authenticated, service_role, postgres;
GRANT ALL ON SEQUENCE public.pool_picks_id_seq TO anon, authenticated, service_role, postgres;

