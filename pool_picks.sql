-- INSTEAD OF DELETE Triggers for Views
CREATE OR REPLACE FUNCTION delete_from_pool_picks_view()
RETURNS TRIGGER AS $$
BEGIN
  DELETE FROM public.pool_picks
  WHERE id = OLD.id
     OR (pool = OLD.pool AND week_no = OLD.week_no AND bookmaker = OLD.bookmaker);
  RETURN OLD;
END;
$$ LANGUAGE plpgsql;

