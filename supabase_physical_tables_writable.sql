-- ALTER TABLE public."weekly pool picks(betking)" DISABLE ROW LEVEL SECURITY;

-- ----------------------------------------------------------------------------
-- STEP 5: REALTIME PUBLICATION
-- ----------------------------------------------------------------------------
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_publication WHERE pubname = 'supabase_realtime') THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE 
            public."weekly pool picks (Bet9ja)",
            public."weekly pool picks(betking)",
            public.picks_bet9ja,
            public.picks_betking;
    END IF;
EXCEPTION
    WHEN duplicate_object THEN NULL;
END $$;

