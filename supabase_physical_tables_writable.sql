-- ============================================================================
-- SUPABASE FIX: CONVERT READ-ONLY VIEWS INTO FULLY WRITABLE PHYSICAL TABLES
-- ============================================================================
-- Why it was "Read Only":
-- 1. In Supabase Table Editor, ALL PostgreSQL Views are automatically flagged as
--    "READ-ONLY". The Supabase Studio UI explicitly disables "Insert Row",
--    "Delete Row", and inline editing on Views.
-- 2. This script drops the views and creates REAL PHYSICAL TABLES with an explicit
--    PRIMARY KEY on `id`, granting full write/delete permissions to all roles.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- STEP 1: DROP OLD READ-ONLY VIEWS
-- ----------------------------------------------------------------------------
DROP VIEW IF EXISTS public."weekly pool picks(Bet9ja)" CASCADE;
DROP VIEW IF EXISTS public."weekly pool picks (Bet9ja)" CASCADE;
DROP VIEW IF EXISTS public."weekly pool picks(bet9ja)" CASCADE;
DROP VIEW IF EXISTS public."weekly pool picks (bet9ja)" CASCADE;
DROP VIEW IF EXISTS public.weekly_pool_picks_bet9ja CASCADE;

DROP VIEW IF EXISTS public."weekly pool picks(betking)" CASCADE;
DROP VIEW IF EXISTS public."weekly pool picks (betking)" CASCADE;
DROP VIEW IF EXISTS public."weekly pool picks(Betking)" CASCADE;
DROP VIEW IF EXISTS public."weekly pool picks (Betking)" CASCADE;
DROP VIEW IF EXISTS public.weekly_pool_picks_betking CASCADE;

-- ----------------------------------------------------------------------------
-- STEP 2: CREATE REAL WRITABLE PHYSICAL TABLE FOR BET9JA
-- ----------------------------------------------------------------------------
DROP TABLE IF EXISTS public."weekly pool picks (Bet9ja)" CASCADE;
DROP TABLE IF EXISTS public.picks_bet9ja CASCADE;

CREATE TABLE public."weekly pool picks (Bet9ja)" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pool INT NOT NULL,
    pool_no INT,
    bet_code VARCHAR(50),
    home VARCHAR(150) NOT NULL,
    away VARCHAR(150) NOT NULL,
    home_win NUMERIC(6,2),
    draw_x NUMERIC(6,2) NOT NULL,
    away_win NUMERIC(6,2),
    bet VARCHAR(20) DEFAULT 'X',
    status VARCHAR(50) DEFAULT 'Saturday',
    kick_off VARCHAR(50) DEFAULT '3:00 PM',
    is_banker BOOLEAN DEFAULT FALSE,
    week_no INT DEFAULT 16,
    week INT DEFAULT 16,
    bookmaker VARCHAR(50) DEFAULT 'bet9ja',
    notes TEXT,
    league VARCHAR(100),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Primary Key & Performance Indexes
CREATE INDEX IF NOT EXISTS idx_bet9ja_pool ON public."weekly pool picks (Bet9ja)"(pool);
CREATE INDEX IF NOT EXISTS idx_bet9ja_week ON public."weekly pool picks (Bet9ja)"(week_no);
CREATE INDEX IF NOT EXISTS idx_bet9ja_code ON public."weekly pool picks (Bet9ja)"(bet_code);

-- Also create standard snake_case physical table picks_bet9ja
CREATE TABLE public.picks_bet9ja (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pool INT NOT NULL,
    pool_no INT,
    bet_code VARCHAR(50),
    home VARCHAR(150) NOT NULL,
    away VARCHAR(150) NOT NULL,
    home_win NUMERIC(6,2),
    draw_x NUMERIC(6,2) NOT NULL,
    away_win NUMERIC(6,2),
    bet VARCHAR(20) DEFAULT 'X',
    status VARCHAR(50) DEFAULT 'Saturday',
    kick_off VARCHAR(50) DEFAULT '3:00 PM',
    is_banker BOOLEAN DEFAULT FALSE,
    week_no INT DEFAULT 16,
    week INT DEFAULT 16,
    bookmaker VARCHAR(50) DEFAULT 'bet9ja',
    notes TEXT,
    league VARCHAR(100),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

