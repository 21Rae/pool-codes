-- ----------------------------------------------------------------------------
-- STEP 4: PERMISSIONS & RLS CONFIGURATION (FULL WRITE & EDIT IN SUPABASE)
-- ----------------------------------------------------------------------------
-- To make Supabase Table Editor 100% editable without any restrictions:
-- We can disable RLS or add open permissive policies. Both are handled below.

-- 1. Grant direct table privileges to all Supabase roles
GRANT ALL ON public."weekly pool picks (Bet9ja)" TO postgres, anon, authenticated, service_role;
GRANT ALL ON public."weekly pool picks(betking)" TO postgres, anon, authenticated, service_role;
GRANT ALL ON public.picks_bet9ja TO postgres, anon, authenticated, service_role;
GRANT ALL ON public.picks_betking TO postgres, anon, authenticated, service_role;

GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO postgres, anon, authenticated, service_role;

-- 2. Enable RLS with 100% permissive CRUD policies (allows Insert, Update, Delete in UI and API)
ALTER TABLE public."weekly pool picks (Bet9ja)" ENABLE ROW LEVEL SECURITY;
ALTER TABLE public."weekly pool picks(betking)" ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.picks_bet9ja ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.picks_betking ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow all operations on weekly pool picks (Bet9ja)"
ON public."weekly pool picks (Bet9ja)" FOR ALL TO public USING (true) WITH CHECK (true);

CREATE POLICY "Allow all operations on weekly pool picks(betking)"
ON public."weekly pool picks(betking)" FOR ALL TO public USING (true) WITH CHECK (true);

CREATE POLICY "Allow all operations on picks_bet9ja"
ON public.picks_bet9ja FOR ALL TO public USING (true) WITH CHECK (true);

CREATE POLICY "Allow all operations on picks_betking"
ON public.picks_betking FOR ALL TO public USING (true) WITH CHECK (true);

