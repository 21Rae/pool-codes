-- ============================================================================
-- SUPABASE SQL SCHEMA: PICKS BET9JA & PICKS BETKING
-- Exact UI Structure Matching FastPoolCodes Customer & Admin Portals
-- Supports:
--   1. Exact UI Columns: pool, bet_code, home, away, home_win, draw_x, away_win,
--                        bet, status, kick_off, is_banker, week_no, bookmaker
--   2. Fixes "Admins cannot delete records" via unrestricted RLS policies and grants
--   3. Compatibility views for legacy naming: "weekly pool picks(Bet9ja)", etc.
--   4. Seed data for Week 16 fixtures matching current UI defaults
-- ============================================================================

-- Enable pgcrypto / uuid extension if needed
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- ============================================================================
-- TABLE 1: picks_bet9ja
-- ============================================================================
DROP TABLE IF EXISTS public.picks_bet9ja CASCADE;

CREATE TABLE public.picks_bet9ja (
    -- Unique Identifier
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- UI Table Columns (in exact UI display order)
    pool INT NOT NULL,                          -- 1. pool: Coupon match number (1 - 49)
    pool_no INT,                                -- Synced alias for pool
    bet_code VARCHAR(50),                       -- 2. bet_code: Bet9ja match booking code (e.g. 1592)
    home VARCHAR(150) NOT NULL,                 -- 3. home: Home team name
    away VARCHAR(150) NOT NULL,                 -- 4. away: Away team name
    home_win NUMERIC(6,2),                      -- 5. home_win: 1 / Home win decimal odds
    draw_x NUMERIC(6,2) NOT NULL,               -- 6. draw_x: X / Draw decimal odds (highlighted)
    away_win NUMERIC(6,2),                      -- 7. away_win: 2 / Away win decimal odds
    bet VARCHAR(20) DEFAULT 'X',                -- 8. bet: Pick recommendation (default 'X')
    status VARCHAR(50) DEFAULT 'Saturday',      -- 9. status: Match timing (Saturday, Sunday, EKO, LKO)
    kick_off VARCHAR(50) DEFAULT '3:00 PM',     -- 10. kick_off: Match kick-off time (e.g. 3:00 PM)
    is_banker BOOLEAN DEFAULT FALSE,            -- 11. is_banker: Banker draw flag (TRUE / FALSE)
    week_no INT DEFAULT 16,                     -- 12. week_no: Pool coupon week (e.g. 16)
    week INT DEFAULT 16,                        -- Synced alias for week_no
    bookmaker VARCHAR(50) DEFAULT 'bet9ja',     -- 13. bookmaker: Bookmaker name ('bet9ja')

    -- Metadata & Auditing
    notes TEXT,                                 -- Match analysis remarks
    league VARCHAR(100),                        -- League competition (e.g. Premier League)
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Indexes for performance
CREATE INDEX IF NOT EXISTS idx_picks_bet9ja_week_no ON public.picks_bet9ja(week_no);
CREATE INDEX IF NOT EXISTS idx_picks_bet9ja_pool ON public.picks_bet9ja(pool);
CREATE INDEX IF NOT EXISTS idx_picks_bet9ja_bet_code ON public.picks_bet9ja(bet_code);
CREATE INDEX IF NOT EXISTS idx_picks_bet9ja_is_banker ON public.picks_bet9ja(is_banker);

