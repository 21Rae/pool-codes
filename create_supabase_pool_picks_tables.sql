-- Trigger functions to allow DELETE directly on views if targeted
CREATE OR REPLACE FUNCTION delete_from_picks_bet9ja_view()
RETURNS TRIGGER AS $$
BEGIN
    DELETE FROM public.picks_bet9ja WHERE id = OLD.id OR (pool = OLD.pool AND week_no = OLD.week_no);
    RETURN OLD;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_delete_view_bet9ja ON public.weekly_pool_picks_bet9ja;
CREATE TRIGGER trg_delete_view_bet9ja
INSTEAD OF DELETE ON public.weekly_pool_picks_bet9ja
FOR EACH ROW EXECUTE FUNCTION delete_from_picks_bet9ja_view();

CREATE OR REPLACE FUNCTION delete_from_picks_betking_view()
RETURNS TRIGGER AS $$
BEGIN
    DELETE FROM public.picks_betking WHERE id = OLD.id OR (pool = OLD.pool AND week_no = OLD.week_no);
    RETURN OLD;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_delete_view_betking ON public.weekly_pool_picks_betking;
CREATE TRIGGER trg_delete_view_betking
INSTEAD OF DELETE ON public.weekly_pool_picks_betking
FOR EACH ROW EXECUTE FUNCTION delete_from_picks_betking_view();

