-- ============================================================================
-- STEP 3: COLUMN SYNC TRIGGER (Keeps pool/pool_no and week/week_no in sync)
-- ============================================================================
CREATE OR REPLACE FUNCTION sync_pool_pick_columns()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.pool IS NULL AND NEW.pool_no IS NOT NULL THEN
        NEW.pool := NEW.pool_no;
    ELSIF NEW.pool_no IS NULL AND NEW.pool IS NOT NULL THEN
        NEW.pool_no := NEW.pool;
    END IF;

    IF NEW.week_no IS NULL AND NEW.week IS NOT NULL THEN
        NEW.week_no := NEW.week;
    ELSIF NEW.week IS NULL AND NEW.week_no IS NOT NULL THEN
        NEW.week := NEW.week_no;
    END IF;

    NEW.updated_at := NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_sync_picks_bet9ja ON public.picks_bet9ja;
CREATE TRIGGER trg_sync_picks_bet9ja
BEFORE INSERT OR UPDATE ON public.picks_bet9ja
FOR EACH ROW EXECUTE FUNCTION sync_pool_pick_columns();

DROP TRIGGER IF EXISTS trg_sync_picks_betking ON public.picks_betking;
CREATE TRIGGER trg_sync_picks_betking
BEFORE INSERT OR UPDATE ON public.picks_betking
FOR EACH ROW EXECUTE FUNCTION sync_pool_pick_columns();

